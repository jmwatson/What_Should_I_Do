WSID.GetRaceNames = function()
    local names = {}
    for _, race in ipairs(WSID.RACE_INFO) do table.insert(names, race.name) end
    return names
end

WSID.GetRaceShortNames = function()
    local short_names={}
    for _, race in ipairs(WSID.RACE_INFO) do table.insert(short_names, race.short_name) end
    return short_names
end

WSID.EncodeRace = function(race)
    if not race or not WSID.RACE_INFO[race] then return WSID.UNKNOWN end
    return WSID.RACE_INFO[race].short_name
end

WSID.GetFaction = function(race)
    if not race or not WSID.RACE_INFO[race] then return WSID.NEUTRAL end
    return WSID.RACE_INFO[race].faction
end

WSID.GetRaceType = function(race)
    if not race or not WSID.RACE_INFO[race] then return "Core" end
    return WSID.RACE_INFO[race].rtype
end

WSID.GetRaceClasses = function(race)
    if not race or not WSID.RACE_INFO[race] then return {} end
    return WSID.RACE_INFO[race].classes
end

